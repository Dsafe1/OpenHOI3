	public const int Types = 52;

	/// <summary>
	/// A tile's quads: four (x, z, u, v) a record, in the records' order. A record whose type is none of the 52 makes no
	/// quad - the original would read past its table - and is counted in <paramref name="skipped"/>.
	/// </summary>
	/// <param name="midX">The tile's middle, 50 × its column + 25.</param>
	/// <param name="midY">The tile's middle, 50 × its row + 25, counted from the south.</param>
	public static List<short> Vertices(IReadOnlyList<CWavePixel> pixels, int midX, int midY, out int skipped)
	{
		var shorts = new List<short>(pixels.Count * 16);
		skipped = 0;
		for (int n = 0; n < pixels.Count; n++)
		{
			CWavePixel pixel = pixels[n];
			if (pixel.Type < 0 || pixel.Type >= Types)
			{
				skipped++;
				continue;
			}
			// Every fourth record of the tile, counted from its first, takes the larger coordinates.
			int uv = n % 4 == 0 ? 16 : 8;
			int x = pixel.X - midX;
			int z = pixel.Y - midY;
			for (int k = 0; k < 4; k++)
			{
				// 2 × (x + corner), the corner in quarters, so (8x + 2 × quarters) / 4, cut towards nought.
				shorts.Add((short)((8 * x + 2 * Table[pixel.Type, 2 * k]) / 4));
				shorts.Add((short)((8 * z + 2 * Table[pixel.Type, 2 * k + 1]) / 4));
				shorts.Add((short)Table[pixel.Type, uv + 2 * k]);
				shorts.Add((short)Table[pixel.Type, uv + 2 * k + 1]);
			}
		}
		return shorts;
	}
